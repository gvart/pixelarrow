#!/usr/bin/env node
/**
 * Regenerates server/src/auth/common-passwords-list.ts (ADR-0008 §2, M-PW-3).
 *
 * Source: SecLists, Passwords/Common-Credentials/xato-net-10-million-passwords-1000000.txt
 * (https://github.com/danielmiessler/SecLists, MIT licence; the underlying
 * dataset is Mark Burnett's "ten million passwords", released to the public
 * domain). The file is sorted from most to least common.
 *
 * The policy refuses anything under 10 characters, so a top-10,000 list taken
 * as is would contribute about 50 usable entries. Instead this keeps the
 * 10,000 MOST COMMON passwords the policy would otherwise accept: in source
 * order, NFKC + lower-case (as checkPasswordPolicy compares), 10 to 128 code
 * points, de-duplicated.
 *
 * Usage (downloads nothing; fetch the file yourself and check its hash):
 *   node server/scripts/common-passwords.mjs path/to/xato-net-10-million-passwords-1000000.txt
 */
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const COUNT = 10_000;
const src = process.argv[2];
if (!src) {
  console.error('usage: node server/scripts/common-passwords.mjs <xato-net-10-million-passwords-1000000.txt>');
  process.exit(1);
}
const raw = readFileSync(src);
const sha = createHash('sha256').update(raw).digest('hex');
const out = [];
const seen = new Set();
for (const line of raw.toString('utf8').split(/\r?\n/)) {
  const pw = line.normalize('NFKC').toLowerCase();
  const len = [...pw].length;
  if (len < 10 || len > 128 || seen.has(pw) || /[\u0000-\u001f\u007f]/.test(pw)) continue;
  seen.add(pw);
  out.push(pw);
  if (out.length === COUNT) break;
}
const target = join(dirname(fileURLToPath(import.meta.url)), '../src/auth/common-passwords-list.ts');
writeFileSync(
  target,
  `// Generated by server/scripts/common-passwords.mjs. Do not edit by hand.\n` +
    `// Source: SecLists xato-net-10-million-passwords-1000000.txt (MIT; data public domain), sha256 ${sha}.\n` +
    `// The ${out.length} most common entries of 10 to 128 characters, NFKC + lower-case, newline-separated.\n` +
    `export const XATO_TOP = ${JSON.stringify(out.join('\n'))};\n`,
);
console.log(`wrote ${out.length} entries to ${target}`);
