// I5a: a class's sheetbuild spec from its review file (docs/v5/pixellab/I5a/<class>/class.json: ramps, parts, tiers and
// the picked attempt and frame fixes of every clip and facing) and the hoplite's clip table (fps, hold, strike, canvas,
// spear), so every class ships the hoplite's timings. Writes docs/v5/pixellab/I5a/<class>/<class>.sheet.json.
// Usage: node scripts/art/pixellab/i5a/spec.mjs <class>
//   class.json: { class, ramps, parts, tiers?, rowsFeet, clips?: { <anim>: { fps?, hold?, strike?, canvas?, spear? } },
//                 picks: { <anim>: { <dir>: "a1" | { attempt, fixes?, frames? } } } }
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..', '..');
const cls = process.argv[2];
const dir = join(ROOT, 'docs/v5/pixellab/I5a', cls);
const c = JSON.parse(readFileSync(join(dir, 'class.json'), 'utf8'));
const hop = JSON.parse(readFileSync(join(ROOT, 'docs/v5/pixellab/I3/hoplite.sheet.json'), 'utf8'));
const DIRS = ['south-east', 'north-east', 'south-west', 'north-west'];
const anims = {};
for (const [anim, picks] of Object.entries(c.picks)) {
  const h = hop.anims[anim] ?? {};
  const o = { ...Object.fromEntries(['fps', 'hold', 'strike', 'canvas', 'spear'].filter((k) => h[k] !== undefined).map((k) => [k, h[k]])), ...(c.clips?.[anim] ?? {}) };
  const dirs = {};
  for (const d of DIRS) {
    if (!picks[d]) continue;
    dirs[d] = typeof picks[d] === 'string' ? { attempt: picks[d] } : { ...picks[d] };
    // a class with no crimson of its own: every reddish pixel of these clips is blood (class.json redClear)
    if (c.redClear?.includes(anim)) {
      const n = c.clips?.[anim]?.frames ?? 12;
      dirs[d].fixes = [...(dirs[d].fixes ?? []), ...Array.from({ length: n }, (_, f) => ({ frame: f, op: 'clear', box: [0, 0, 127, 127], red: true, why: 'blood (the class has no crimson)' }))];
    }
  }
  if (Object.keys(dirs).length < 4) { console.log(`  ${anim}: ${Object.keys(dirs).length}/4 facings, left out`); continue; }
  anims[anim] = { ...o, dirs };
}
const spec = {
  $doc: `I5a ${cls} sheet spec (generated by scripts/art/pixellab/i5a/spec.mjs from class.json). Rebuild: node scripts/art/pixellab/fetchjobs.mjs docs/v5/pixellab/I5a/${cls}/jobs.json docs/v5/pixellab/I5a/raw/${cls} && node scripts/art/pixellab/sheetbuild.mjs docs/v5/pixellab/I5a/${cls}/${cls}.sheet.json`,
  class: cls,
  raw: `docs/v5/pixellab/I5a/raw/${cls}`,
  out: `src/assets/sheets/${cls}`,
  scale: hop.scale,
  ramps: c.ramps,
  parts: c.parts,
  ...Object.fromEntries(['crest', 'emblem', 'stature', 'metalKind', 'metalSlots', 'spear', 'greyCut'].filter((k) => c[k] !== undefined).map((k) => [k, c[k]])),
  rowsFeet: c.rowsFeet,
  canvases: hop.canvases,
  anims,
  tiers: c.tiers ?? hop.tiers,
};
writeFileSync(join(dir, `${cls}.sheet.json`), JSON.stringify(spec, null, 1) + '\n');
console.log(`${cls}: ${Object.keys(anims).length} clips -> ${join(dir, `${cls}.sheet.json`)}`);
