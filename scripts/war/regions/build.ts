/**
 * Builds the world regions (docs/WAR.md "World"): the hand-made ones (scripts/war/regions/<id>.ts) and the per-biome
 * drafts (./drafts.ts), writing src/war/regions/<id>.json + <id>.spots.ts and the list src/war/regions/index.ts.
 *
 *   node scripts/war/regions/build.ts [id,id...] [--png dir]
 *
 * --png writes a top-down preview per region (terrain colours shaded by height, cliffs dark, objects, lairs red,
 * claim points yellow, entries magenta, spots white) for a quick look without the sandbox.
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { preview } from './preview.ts';
import { checkWorld, WORLD } from './world.ts';
import { writeRegion, type RegionDef } from './kit.ts';
import { DRAFTS } from './drafts.ts';
import elaia from './elaia.ts';
import kyrene from './kyrene.ts';
import dodona from './dodona.ts';
import skythia from './skythia.ts';
import kleisoura from './kleisoura.ts';
import omphalos from './omphalos.ts';

const HAND: RegionDef[] = [elaia, kyrene, dodona, skythia, kleisoura, omphalos];
const ALL = new Map<string, RegionDef>([...DRAFTS, ...HAND].map((d) => [d.id, d]));
const bad = checkWorld();
if (bad.length) throw new Error(`asymmetric adjacency: ${bad.join(', ')}`);
for (const r of WORLD) if (!ALL.has(r.id)) throw new Error(`no script for ${r.id}`);

const args = process.argv.slice(2);
const pngAt = args.indexOf('--png');
const pngDir = pngAt >= 0 ? args[pngAt + 1] : null;
const ids = args.filter((a, i) => !a.startsWith('--') && (pngAt < 0 || i !== pngAt + 1))[0]?.split(',') ?? [...ALL.keys()];
let total = 0;
for (const id of ids) {
  const def = ALL.get(id);
  if (!def) throw new Error(`unknown region ${id}`);
  const t0 = Date.now(), b = writeRegion(def);
  total += b.bytes;
  console.log(`${id}${def.draft ? ' (draft)' : ''}: ${(b.bytes / 1024).toFixed(0)} KB in ${((Date.now() - t0) / 1000).toFixed(1)} s; ${b.log.join('; ')}`);
  if (pngDir) preview(b.json, b.spots, join(pngDir, `${id}.png`));
}
console.log(`total ${(total / 1024 / 1024).toFixed(2)} MB for ${ids.length} regions`);

// the region list the sandbox offers (src/war/view/devPanel.ts)
const list = WORLD.map((r) => `  { id: '${r.id}', name: ${JSON.stringify(r.name)}, role: '${r.role}', draft: ${!!ALL.get(r.id)!.draft} },`);
writeFileSync(
  fileURLToPath(new URL('../../../src/war/regions/index.ts', import.meta.url)),
  `// Generated by scripts/war/regions/build.ts: the world regions (docs/WAR.md), each loaded lazily by src/war/region/loader.ts.\n` +
    `export const WORLD_REGIONS = [\n${list.join('\n')}\n] as const;\n`,
);
