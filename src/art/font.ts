export const FONT_LINE_HEIGHT = 9;
export const FONT_CELL_H = 9;

export interface GlyphInfo {
  ch: string;
  x: number;
  y: number;
  w: number;
}

/** Render the glyph atlas (white glyphs, plus optional 1px drop shadow colour). */
export function renderFontAtlas(color: number, shadow?: number): { canvas: HTMLCanvasElement; glyphs: GlyphInfo[] } {
  const chars = Object.keys(G);
  const cellW = 7;
  const cols = 16;
  const rows = Math.ceil(chars.length / cols);
  const canvas = document.createElement('canvas');
  canvas.width = cols * cellW;
  canvas.height = rows * FONT_CELL_H;
  const ctx = canvas.getContext('2d')!;
  const img = ctx.createImageData(canvas.width, canvas.height);
  const put = (x: number, y: number, c: number) => {
    const i = (y * canvas.width + x) * 4;
    img.data[i] = (c >> 16) & 255;
    img.data[i + 1] = (c >> 8) & 255;
    img.data[i + 2] = c & 255;
    img.data[i + 3] = 255;
  };
  const glyphs: GlyphInfo[] = [];
  chars.forEach((ch, idx) => {
    const gx = (idx % cols) * cellW;
    const gy = Math.floor(idx / cols) * FONT_CELL_H;
    const rowsG = G[ch];
    const w = rowsG[0].length;
    if (shadow !== undefined) {
      rowsG.forEach((r, y) => [...r].forEach((p, x) => p === '#' && put(gx + x + 1, gy + y + 1, shadow)));
    }
    rowsG.forEach((r, y) => [...r].forEach((p, x) => p === '#' && put(gx + x, gy + y, color)));
    glyphs.push({ ch, x: gx, y: gy, w: w + (shadow !== undefined ? 1 : 0) });
  });
  ctx.putImageData(img, 0, 0);
  return { canvas, glyphs };
}
